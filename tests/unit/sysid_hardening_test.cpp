constexpr double eps = std::numeric_limits<double>::epsilon();

/// Noise standard deviations of the generated records, named so the bounds below
/// read as functions of the noise rather than as constants.
constexpr double noise_sd_fine = 0.001;
constexpr double noise_sd_coarse = 0.01;

/// Confidence multiplier on every standard-error bound in this file.
///
/// Three standard errors. The generators are seeded, so nothing here is flaky
/// and the multiplier is not protecting against a rerun -- it is the statement
/// that the assertion is about the estimator's sampling distribution and not
/// about this one realization of it. Each use records the realized ratio.
constexpr double confidence_multiplier = 3.0;

/// Relative allowance on a residual-norm bound built from a finite record.
///
/// A sum of n squared residuals has a relative spread of the square root of two
/// over n about its expectation, so a floor derived from the noise standard
/// deviation is met only to within that spread. Carried at the same three
/// standard errors as the parameter bounds.
auto residual_norm_allowance(int samples) -> double
{
    return confidence_multiplier * std::sqrt(2.0 / static_cast<double>(samples));
}

/// Index of the largest step down between consecutive singular values.
///
/// A record generated by a system of order p has p singular values well above
/// the noise and the rest at it, so the largest step sits at index p - 1. A
/// record with no system has no such step at the front. Comparing the routine's
/// own numbers with each other needs no threshold.
auto largest_singular_value_gap(Eigen::VectorXd const& sv) -> Eigen::Index
{
    Eigen::Index best = 0;
    double best_ratio = 0.0;
    for (Eigen::Index k = 0; k + 1 < sv.size(); ++k) {
        double const ratio = sv(k) / sv(k + 1);
        if (ratio > best_ratio) {
            best_ratio = ratio;
            best = k;
        }
    }
    return best;
}

