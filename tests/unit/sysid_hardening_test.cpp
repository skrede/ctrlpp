// What the oracles in this file decide.
//
// Identification is a statistical estimate from a noisy record, so the bounds
// here are derived from the noise that generated the record rather than fitted
// to the answer that came back:
//
//  * Where a configuration is out of domain the construction is REFUSED with the
//    enumerator that names the cause. Where it is degenerate but in domain -- a
//    zero-confidence prior, a non-finite regressor -- the update is a no-op and
//    the parameters stay BITWISE at their initial values.
//  * Where a case name promises identified coefficients, the coefficients are
//    asserted, against the parameter standard error the noise magnitude, the
//    sample count and the accumulated regressor second moment imply, times a
//    stated confidence multiplier. Not against a band two decades looser.
//  * Where a fit metric is asserted, its floor is derived from the noise model
//    the record was generated under. That floor differs between the two model
//    families and the difference is real: the recursive record carries its noise
//    as PROCESS noise, so a free-run simulation amplifies it by one over the
//    square root of one minus the pole squared, while the state-space records
//    carry it as measurement noise on the output alone, which a free run does
//    not amplify at all.
//  * The subspace method returns a SIMILARITY-TRANSFORMED realization, so its
//    coefficients cannot be compared with the ones that generated the data. The
//    eigenvalue and the direct-current gain can, and those are what is asserted.
//  * The companion superdiagonal is exactly one. It is structural, not merely
//    finite, and if it is not one the initialization loop the case exists to
//    exercise is wrong.
//
// What they deliberately do not decide. The rank-deficient batch case does not
// pin which member of the solution set the decomposition selects: measured, it
// is not the minimum-norm one, so naming that would state something false. What
// it asserts instead is the property every member shares, that the fitted model
// reproduces the record. And no case asserts a rank threshold for a random
// Hankel matrix; deriving one is separate numerical work.

